//! Латинско-кириллические двойники в именах платформы (issue #18).
//!
//! В справке платформы встречаются опечатки, неотличимые на экране: значение
//! `РежимОткрытияОкнаФормы.БлокироватьВесьИнтерфейс` в справке 8.3.17 записано
//! с ЛАТИНСКОЙ `c` (U+0063), тогда как платформа принимает кириллическую.
//! Проверка сравнивала имена буквально, поэтому корректный код получал
//! `unknown_enum_value` с `confidence: high` (его пропускает даже профиль
//! `strict`), а `suggestion` предлагал имя с латиницей — платформа такое имя
//! отвергает, то есть подсказка ломала рабочий код, и причину невозможно
//! заметить глазами.
//!
//! Отсюда два правила:
//!
//! 1. Имена сравниваются ПОСЛЕ приведения двойников к одному алфавиту
//!    ([`same_after_fold`]): написанное в коде и записанное в справке имя,
//!    различающиеся только алфавитом буквы, считаются одним именем — находки нет.
//!    Размен осознанный: код с «неправильной» буквой мы тоже пропустим молча, но
//!    это безопаснее ложной находки `high` с ломающей подсказкой.
//! 2. Имя из справки, где смешаны алфавиты ([`is_mixed_alphabet`]), в подсказку
//!    не попадает вовсе: это почти наверняка опечатка справки, а не то, что нужно
//!    написать в коде.

/// Привести латинские двойники кириллических букв к кириллице.
///
/// Приведение одностороннее (латиница → кириллица) и регистр сохраняет: для
/// сравнения этого достаточно, а обратное преобразование смешало бы алфавиты там,
/// где они различимы осмысленно.
pub fn fold_lookalikes(name: &str) -> String {
    name.chars().map(fold_char).collect()
}

fn fold_char(c: char) -> char {
    match c {
        'a' => 'а',
        'c' => 'с',
        'e' => 'е',
        'o' => 'о',
        'p' => 'р',
        'x' => 'х',
        'y' => 'у',
        'k' => 'к',
        'm' => 'м',
        't' => 'т',
        'h' => 'н',
        'b' => 'в',
        'A' => 'А',
        'C' => 'С',
        'E' => 'Е',
        'O' => 'О',
        'P' => 'Р',
        'X' => 'Х',
        'Y' => 'У',
        'K' => 'К',
        'M' => 'М',
        'T' => 'Т',
        'H' => 'Н',
        'B' => 'В',
        other => other,
    }
}

/// Имена совпадают после приведения двойников? Регистр не важен.
pub fn same_after_fold(left: &str, right: &str) -> bool {
    if left.is_empty() || right.is_empty() {
        return false;
    }
    fold_lookalikes(&left.to_lowercase()) == fold_lookalikes(&right.to_lowercase())
}

/// В имени смешаны кириллица и латиница?
///
/// Такое имя из справки платформы в подсказку не годится: в коде его повторят
/// дословно, а платформа его не примет.
pub fn is_mixed_alphabet(name: &str) -> bool {
    let cyrillic = name
        .chars()
        .any(|c| matches!(c, 'а'..='я' | 'А'..='Я' | 'ё' | 'Ё'));
    let latin = name.chars().any(|c| c.is_ascii_alphabetic());
    cyrillic && latin
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn issue18_latin_c_equals_cyrillic_s() {
        // Значение из справки 8.3.17 с латинской `c` и корректное написание в коде.
        let from_help = "БлокироватьВеcьИнтерфейс";
        let from_code = "БлокироватьВесьИнтерфейс";
        assert_ne!(from_help, from_code, "строки различаются");
        assert!(same_after_fold(from_help, from_code));
        assert!(same_after_fold("Независимый", "независимый"), "регистр");
    }

    #[test]
    fn different_names_are_not_folded_together() {
        assert!(!same_after_fold("БлокироватьОкноВладельца", "Независимый"));
        assert!(!same_after_fold("", "Независимый"));
        assert!(!same_after_fold("Блокировать", "Блокироватьь"));
    }

    #[test]
    fn mixed_alphabet_is_detected() {
        // Смешанные алфавиты бывают и законными (`HTTPСоединение`, `COMОбъект`) —
        // правило используется только для фильтра подсказок, не для проверок.
        assert!(is_mixed_alphabet("БлокироватьВеcьИнтерфейс"));
        assert!(is_mixed_alphabet("HTTPСоединение"));
        assert!(!is_mixed_alphabet("БлокироватьВесьИнтерфейс"));
        assert!(!is_mixed_alphabet("StrFind"));
        assert!(!is_mixed_alphabet("Строка1"));
    }
}
